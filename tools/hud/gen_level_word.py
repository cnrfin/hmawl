"""'Level up' for the skill pop-up (step 2): glyph rects in the HUD font (opguide.tpl texture 3), same rules as
build_skill_hud.py's words. usage: gen_level_word.py glyph_meta.json OUT.h"""
import json, sys
G = json.load(open(sys.argv[1])); code = {cd: i for i, cd in enumerate(G['codes'])}
def gl(ch):
    cd = 0x0B + ord(ch) - 65 if ch.isupper() else 0xD8 + ord(ch) - 97
    i = code[cd]; cx, cy = G['cells'][i]; lft, w = G['adv'][i]; C = G['cell']
    return ((cx + lft) / G['aw'], cy / G['ah'], (cx + lft + w) / G['aw'], (cy + C) / G['ah'], w, C)
wd = 'Level up'
h = ['/* generated by tools/hud/gen_level_word.py */', 'static const struct glyph WORD2[] = {  /* "%s" (0 w = space) */' % wd]
for ch in wd:
    h.append('    {0, 0, 0, 0, 0, 0},' if ch == ' ' else '    {%ff, %ff, %ff, %ff, %d, %d},  /* %s */' % (gl(ch) + (ch,)))
h += ['};', '#define WORD2_N %d' % len(wd)]
open(sys.argv[2], 'w').write('\n'.join(h) + '\n')
