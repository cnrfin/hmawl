"""Joe's lines -> game/joe_lines.h for pm.c's talk animation: per line its face (0 neutral, 1 angry, 2 happy,
3 sad) and the letters on each page (pm.c times the mouth flaps and hand gestures to the typing).
The events set counter 49 = line index + 1 just before each line (build_joe_trade.py / build_joe_talk.py).
usage: gen_joe_lines.py game/joe_lines.h"""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_joe_mes import TEXT
FACE = {'what': 1, 'bought': 2, 'gift': 2, 'gift_again': 2, 'intro': 2}
MAXP = 4
rows = []
for k, t in TEXT:
    pages = [len(re.sub(r'<price>', '0000', re.sub(r'<(wait|yesno)>', '', p)).replace('\n', '')) for p in t.split('<page>')]
    assert len(pages) <= MAXP
    rows.append('    { %d, %d, { %s } },   /* %s */' % (FACE.get(k, 0), len(pages), ', '.join(map(str, pages + [0] * (MAXP - len(pages)))), k))
out = ['/* generated by gen_joe_lines.py from build_joe_mes.py: face, pages, letters per page */',
       '#define JL_N %d' % len(TEXT), 'static const struct { unsigned char face, pages, len[%d]; } joe_lines[JL_N] = {' % MAXP] + rows + ['};']
out += ['#define JL_%s %d' % (k.upper(), i + 1) for i, (k, _) in enumerate(TEXT)]
open(sys.argv[1], 'w').write('\n'.join(out) + '\n'); print('\n'.join(out))
