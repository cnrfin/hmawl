"""Joe's visit route from the valley path network (path_WorldMap.pth with the dig-site bridge): three legs
glued into one polyline; joe_route.h gives the points, segment lengths and the leg boundaries (distances)."""
import json, numpy as np, heapq, sys
N=np.load('N.npy'); L=json.load(open('net.json'))['L']
def dij(a,b,ban=()):
    dist={a:0}; prev={}; pq=[(0,a)]
    while pq:
        d,u=heapq.heappop(pq)
        if u==b: break
        if d>dist[u]: continue
        for v in L[u]:
            if v in ban: continue
            nd=d+np.hypot(*(N[u]-N[v]))
            if nd<dist.get(v,1e9): dist[v]=nd; prev[v]=u; heapq.heappush(pq,(nd,v))
    p=[b]
    while p[-1]!=a: p.append(prev[p[-1]])
    return p[::-1]
START=463; DIG=469; BENCH=285
leg1=dij(START,DIG); leg2=dij(DIG,BENCH,ban=(354,)); leg3=dij(BENCH,START)
pts=leg1+leg2[1:]+leg3[1:]
P=N[pts]; seg=np.hypot(*(P[1:]-P[:-1]).T)
b1=seg[:len(leg1)-1].sum(); b2=b1+seg[len(leg1)-1:len(leg1)+len(leg2)-2].sum(); tot=seg.sum()
out=['/* generated by tools/joe/visit/gen_route.py: path network nodes '+' '.join(map(str,pts))+' */',
     '#define JR_N %d'%len(pts),'#define JR_DIG %.4ff     /* distance at the dig-site end of the bridge (node 469) */'%b1,
     '#define JR_BENCH %.4ff   /* distance at the bench (node 285) */'%b2,'#define JR_LEN %.4ff'%tot,
     'static const float jr_pt[JR_N][2] = {'+', '.join('{ %.3ff, %.3ff }'%tuple(p) for p in P)+' };',
     'static const float jr_seg[JR_N - 1] = {'+', '.join('%.4ff'%s for s in seg)+' };']
open(sys.argv[1],'w').write('\n'.join(out)+'\n')
print(len(pts),round(b1,2),round(b2-b1,2),round(tot-b2,2))
