#!/usr/bin/env python3
"""The alien's standing pose (T2 arms, the hunch, head forward) as local quaternions for zt.c's pose layer.
The design's pose is a world-frame rotation D[n] per joint (R[n] = R[parent] D[n], body_candidates.pose); the game
composes model = parent_model * local, and Celia's nodes have rest rotations, so
    local[n] = Mrest[p]^T D[n] Mrest[p] Lrest[n]      (Mrest: rest model rotations, Lrest: rest local rotations).
Checked by rebuilding the posed joints from the table + the built skeleton and comparing with body_candidates' FK.
usage: gen_pose.py OUT.h"""
import sys, os, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
os.environ['SET'] = 'none'
_argv = sys.argv; sys.argv = ['x', '/tmp']
exec(open(os.path.join(HERE, 'body_candidates.py')).read().split("try: font")[0])
sys.argv = _argv
from awlchar import qmat

def m2q(m):
    t = m[0, 0] + m[1, 1] + m[2, 2]
    if t > 0:
        s = 0.5 / np.sqrt(t + 1); return np.array([(m[2, 1] - m[1, 2]) * s, (m[0, 2] - m[2, 0]) * s, (m[1, 0] - m[0, 1]) * s, 0.25 / s])
    if m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = 2 * np.sqrt(1 + m[0, 0] - m[1, 1] - m[2, 2]); return np.array([0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s, (m[2, 1] - m[1, 2]) / s])
    if m[1, 1] > m[2, 2]:
        s = 2 * np.sqrt(1 + m[1, 1] - m[0, 0] - m[2, 2]); return np.array([(m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s, (m[0, 2] - m[2, 0]) / s])
    s = 2 * np.sqrt(1 + m[2, 2] - m[0, 0] - m[1, 1]); return np.array([(m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s, (m[1, 0] - m[0, 1]) / s])

