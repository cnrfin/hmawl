print('max joint error %.2e, max rotation error %.2e' % (err, rerr))
assert err < 1e-4 and rerr < 1e-4
h = ['/* generated by tools/alien/gen_pose.py: the alien\'s standing pose (T2 arms, hunch, head forward), local */',
     '/* quaternions (x, y, z, w) for Celia\'s 49 nodes (zt.c ht_bone, owl slot) */', '#define AL_NODES %d' % len(Q),
     'static const float AL_Q[AL_NODES][4] = {']
h += ['    {%.6ff, %.6ff, %.6ff, %.6ff},' % tuple(q) for q in Q] + ['};']
open(sys.argv[1], 'w').write('\n'.join(h) + '\n'); print('wrote', sys.argv[1])
