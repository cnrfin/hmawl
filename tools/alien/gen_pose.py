Mrest = [None] * len(nodes)
for n in range(len(nodes)):
    p = PAR[n]; Mrest[n] = Lrest[n] if p < 0 else Mrest[p] @ Lrest[n]
Q = []
for n in range(len(nodes)):
    p = PAR[n]; Dn = D.get(n, np.eye(3))
    L = Dn @ Lrest[n] if p < 0 else Mrest[p].T @ Dn @ Mrest[p] @ Lrest[n]
    q = m2q(L); Q.append(q / np.linalg.norm(q))
# check: model rotations / joint positions from the table vs the design's FK (lengths as built)
M = [None] * len(nodes); tj = [None] * len(nodes)
for n in range(len(nodes)):
    p = PAR[n]; Ln = qmat(Q[n]); T = np.array(nodes[n]['T']) * LEN.get(n, 1.0)
    if p < 0: M[n] = Ln; tj[n] = T
    else: M[n] = M[p] @ Ln; tj[n] = M[p] @ T + tj[p]
pose(dict(len=LEN, rot=D), VA); R_, t_ = pose.last
err = max(np.linalg.norm(tj[n] - t_[n]) for n in range(len(nodes)))
