#!/usr/bin/env python3
"""Goddess quest text (gq1). Works on the disc's own files, keeping every other message byte for byte:
  - debug.mes (file 0x32): four quest lines in free (4-byte) entries; size kept (taken from the trailing padding)
  - Message.arc item.mes + the loose item.mes: item 0x448 "Strange Fossil" -> "Mermaid Fossil"
  - itemdoc03.mes: its description (entry 0x448 - 0x3ED)
Writes OUTDIR/{debug.mes, Message.arc, item.mes, itemdoc03.mes} and gq_mes.h (message ids for spring.c).
usage: build_gq_text.py debug.mes Message.arc item.mes itemdoc03.mes OUTDIR"""
import sys, os, struct, hashlib
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'weapons'))
from add_weapon_text import enc, mes_read, mes_write, u8_replace, u8_get
FOSSIL = 0x448
NAME = "Mermaid Fossil"
DESC = "Webbed hands and a\nnear-human face..."   # gq2: two short lines (three scrolled away in the R box)
LINES = {   # gq4: at most 2 lines of ~20 characters (the box shows 2; a third scrolled away); 30 = wait for A
    'SHIMMER': "The water shimmers...",
    'GLOW':    "The spring glows.\nSomething is missing.",
    'NOTYET':  "The water pushes it\nback. Not yet...",
    'SUMMON':  "A warm light rises\nfrom the spring...",
}
def pad4(b):
    b = bytearray(b) + b'\x00'
    while len(b) % 4: b.append(0)
    return bytes(b)

def main():
    dbg_in, arc_in, item_in, doc_in, out = sys.argv[1:6]
    os.makedirs(out, exist_ok=True)
    # debug.mes
    d = open(dbg_in, 'rb').read(); ents = mes_read(d)
    free = [i for i, e in enumerate(ents) if e == b'\0\0\0\0' and i < len(ents) - 1]
    assert len(free) >= len(LINES), 'not enough free debug.mes entries (%d)' % len(free)
    ids = {}
    for (k, s), i in zip(LINES.items(), free):
        ents[i] = pad4(enc(s) + b'\x30'); ids[k] = i
    grow = sum(map(len, ents)) - sum(map(len, mes_read(d)))
    assert set(ents[-1]) == {0} and len(ents[-1]) > grow, 'no zero padding at the end of debug.mes'
    ents[-1] = ents[-1][:len(ents[-1]) - grow]
    nd = mes_write(ents); nd += bytes(len(d) - len(nd)); assert len(nd) == len(d)
    open(os.path.join(out, 'debug.mes'), 'wb').write(nd)
    # names
    def rename(mes):
        m = mes_read(mes); z = len(m[FOSSIL]) - len(m[FOSSIL].rstrip(b'\0'))
        m[FOSSIL] = enc(NAME) + b'\0' * max(z, 1); return mes_write(m)
    arc = open(arc_in, 'rb').read()
    na = u8_replace(arc, 'item.mes', rename(u8_get(arc, 'item.mes')))
    open(os.path.join(out, 'Message.arc'), 'wb').write(na)
    open(os.path.join(out, 'item.mes'), 'wb').write(rename(open(item_in, 'rb').read()))
    doc = mes_read(open(doc_in, 'rb').read()); m = doc[FOSSIL - 0x3ED]
    assert m[0] == 0x13 and m[1] == 0x25 and m[5] == 0x17, m[:8].hex()     # <hl><25:id>\n</hl>, as add_weapon_text
    doc[FOSSIL - 0x3ED] = m[:6] + enc(DESC) + b'\x30\x00'
    open(os.path.join(out, 'itemdoc03.mes'), 'wb').write(mes_write(doc))
    h = ['/* generated by tools/goddess/quest/build_gq_text.py: goddess quest lines in debug.mes (file 0x32) */']
    h += ['#define GQ_MSG_%s 0x%X' % (k, v) for k, v in ids.items()]
    open(os.path.join(out, 'gq_mes.h'), 'w').write('\n'.join(h) + '\n')
    for f in ('debug.mes', 'Message.arc', 'item.mes', 'itemdoc03.mes'):
        print(f, hashlib.sha1(open(os.path.join(out, f), 'rb').read()).hexdigest()[:8])
    print(ids)

if __name__ == '__main__':
    main()
