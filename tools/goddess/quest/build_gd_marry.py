#!/usr/bin/env python3
"""Marrying the goddess (w1): Nami's farewell, event 414 appended to Common.arc. pm.c (gd_marry_frame) starts it the day
after the proposal, 6:00-16:00, when Nami (character 4) is out on the player's map near him, with:
  20-25 camera eye / target x 128 (cmd_14 / cmd_15)
  26 / 27 facing degrees: the farmer -> Nami, Nami -> the farmer (cmd_59)
The two lines are batch 4's N1 / N2 (debug.mes, ids from gd_daily.h, built by build_gd_daily.py), spoken as Nami
(speaker 4: her name plate); then a fade to black, Nami hidden (cmd_5A(4, 0)) and back. pm.c then keeps her daily
routine off (she has left the valley).
usage: build_gd_marry.py Common.arc gd_daily.h OUTDIR   (Common.arc: the jm2 build, events to 413)
needs scratchpad/event (scrasm, clzc, clz, loadarc) via EVTOOLS. Writes Common.arc and gd_marry.h."""
import sys, os, struct, re, hashlib
EV = os.environ.get('EVTOOLS', '/tmp/claude-0/-home-user/93ad7071-c0f2-50fe-8edf-5fd70c4d5f13/scratchpad/event')
sys.path.insert(0, EV); sys.path.insert(0, os.path.dirname(EV))
from scrasm import Asm
from clzc import clz_compress
from clz import clz_decompress
from loadarc import load, parse
common_in, hdr_in, outdir = sys.argv[1:4]
os.makedirs(outdir, exist_ok=True)
ids = {m.group(1): int(m.group(2), 16) for m in re.finditer(r'#define GDL_(\w+) 0x([0-9A-F]+)', open(hdr_in).read())}
FILE = 0x32
a = Asm(); L = a.new
a.sys(0x10)
for base, cmd in ((20, 0x14), (23, 0x15)):                   # camera from counters 20-25 (pm.c)
    for k in range(3): a.num(base + k); a.sys(0x95); a.num(128); a.emit('div')
    a.sys(cmd)
a.sys(0x00)
def face(ch, c): a.num(ch); a.num(c); a.sys(0x95); a.sys(0x59)
face(0, 26); face(4, 27)
def say(k):                                                  # cmd_04(debug.mes, line, speaker 4 = Nami's plate)
    top = L('msg'); a.label(top); a.sys(0x00)
    a.num(FILE); a.num(ids[k]); a.num(4); a.sys(0x04); a.num(0); a.emit('cmp'); a.jz(top)
say('N1'); say('N2')
def fade(cmd):                                               # cmd_0B out / cmd_0C in: black, 0.5 s
    a.num(0); a.raw(64); a.sys(cmd)
    top = L('fade'); a.label(top); a.sys(0x00); a.sys(0x0D); a.jnz(top)
fade(0x0B)
a.num(4); a.num(0); a.sys(0x5A)                              # Nami hidden (gone)
fade(0x0C)
a.emit('end'); a.emit('end')
script = a.build()
ins, ch = parse(script); assert len(ins) == len(a.ins)

u = open(common_in, 'rb').read()
be = lambda b, o: struct.unpack_from('>I', b, o)[0]
root, hsize, dstart = be(u, 4), be(u, 8), be(u, 12)
n = be(u, root + 8); st = root + 12 * n
assert n == 114, 'expected the jm2 Common.arc (events to 413): %d nodes' % n
names = bytes(u[st:root + hsize])
nodes = [bytearray(u[root + 12 * i:root + 12 * i + 12]) for i in range(n)]
raws = [clz_decompress(u[be(u, root + 12 * i + 4):be(u, root + 12 * i + 4) + be(u, root + 12 * i + 8)]) for i in range(1, n)]
raws.append(script)
al = lambda x: (x + 0x1F) & ~0x1F
name_off = len(names.rstrip(b'\0')) + 1
names2 = names[:name_off] + b'@\0'
nodes.append(bytearray(struct.pack('>III', name_off, 0, 0)))
struct.pack_into('>I', nodes[0], 8, n + 1)
hlen = 12 * (n + 1) + len(names2)
dstart = max(dstart, al(root + hlen))
data = bytearray(); offs = []
for r in raws:
    c = clz_compress(r); offs.append((dstart + len(data), len(c))); data += c + bytes(al(len(c)) - len(c))
for i, (o, sz) in enumerate(offs, 1): struct.pack_into('>II', nodes[i], 4, o, sz)
hdr = b''.join(nodes) + names2
out = bytearray(u[:root]) + hdr
struct.pack_into('>I', out, 8, len(hdr)); struct.pack_into('>I', out, 12, dstart)
out += bytes(dstart - len(out)); out += data
open(os.path.join(outdir, 'Common.arc'), 'wb').write(bytes(out))
_, fs = load(os.path.join(outdir, 'Common.arc')); assert [b for _, b in fs] == raws
EVENT = 300 + len(fs)
open(os.path.join(outdir, 'gd_marry.h'), 'w').write(
    '/* generated by tools/goddess/quest/build_gd_marry.py */\n#define GM_EV_BYE %d\n#define GM_C_FACE0 26\n#define GM_C_FACE4 27\n' % EVENT)
b = open(os.path.join(outdir, 'Common.arc'), 'rb').read()
print('event %d; Common.arc %d %s' % (EVENT, len(b), hashlib.sha1(b).hexdigest()[:8]))
